def main() -> None:
    episodes = [e.build() for e in pytest_family() + gha_family() + config_family() + misc()]
    bundle = {
        "schema_version": "experience-bundle.v1",
        "export_id": "skill-foundry-demo-2026-09",
        "exported_at": "2026-09-30T00:00:00Z",
        "episodes": episodes,
        "extensions": {"skill_foundry.corpus_version": "demo-corpus.v1"},
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(bundle, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(episodes)} episodes)")
    late = [e.build() for e in late_arrivals()]
    LATE.write_text("".join(json.dumps(e) + "\n" for e in late), encoding="utf-8")
    print(f"wrote {LATE} ({len(late)} episodes, generic JSONL)")


