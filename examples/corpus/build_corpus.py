"""Generate the synthetic demo corpus as a canonical experience-bundle.v1 file.

Run:  uv run python examples/corpus/build_corpus.py

Everything here is synthetic and written for this repository. The generator is
deterministic so the committed bundle can be regenerated byte-for-byte. The
corpus deliberately contains:

* three task families with several independent verified successes each, spread
  over different repositories and environments;
* near-duplicate re-runs of the same task (they must collapse into one
  independence unit, not count as extra confirmations);
* a ``verified_success`` claim whose only evidence is an un-linked command
  (must be qualified as ``recorded``, not ``verified``);
* a ``claimed_success`` episode (``self_reported``);
* stale evidence (tested revision differs from the episode revision);
* verified failures used as counterexamples / contraindications;
* a prompt-injection-bearing episode (must be quarantined);
* a "bridge" episode mixing two families (must not chain the families together);
* a one-off fix (must be classified one_off, not reusable).

Hidden evaluation tasks live in ``examples/eval`` and are never part of this file.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

OUT = Path(__file__).resolve().parent.parent / "bundles" / "demo-bundle.v1.json"
LATE = OUT.parent / "late-arrivals.jsonl"
ACC = "skill_foundry.acceptance"


def rev(seed: str) -> str:
    return hashlib.sha1(seed.encode()).hexdigest()  # noqa: S324 - deterministic fake SHA


def ts(day: int, hour: int = 10) -> str:
    return f"2026-09-{day:02d}T{hour:02d}:00:00Z"


class Ep:
    def __init__(
        self,
        episode_id: str,
        task: str,
        repo: str,
        revision_seed: str,
        *,
        runtime: str,
        platform: str,
        versions: dict[str, str],
        day: int,
        lineage: str | None = None,
    ):
        self.id = episode_id
        self.task = task
        self.revision = rev(revision_seed)
        self.env: dict[str, Any] = {
            "repo_id": repo,
            "revision": self.revision,
            "versions": versions,
            "runtime": runtime,
            "platform": platform,
        }
        self.day = day
        self.lineage = lineage
        self.events: list[str] = []
        self.observations: list[dict[str, Any]] = []
        self.attempts: list[dict[str, Any]] = []
        self.evidence: list[dict[str, Any]] = []
        self.lessons: list[dict[str, Any]] = []
        self.status = "verified_success"

    def _event(self) -> str:
        e = f"{self.id}-e{len(self.events) + 1:02d}"
        self.events.append(e)
        return e

    def obs(self, kind: str, summary: str, error_code: str | None = None) -> Ep:
        self.observations.append(
            {
                "observation_id": f"o{len(self.observations) + 1}",
                "kind": kind,
                "summary": summary,
                "error_code": error_code,
                "timestamp": ts(self.day, 9),
                "source_event_ids": [self._event()],
            }
        )
        return self

    def att(self, action: str, status: str = "completed", result: str | None = None) -> Ep:
        self.attempts.append(
            {
                "attempt_id": f"a{len(self.attempts) + 1}",
                "action_summary": action,
                "status": status,
                "result_summary": result,
                "source_event_ids": [self._event()],
            }
        )
        return self

    def ev(
        self,
        kind: str,
        summary: str,
        exit_code: int | None,
        *,
        criteria: list[str] | None = None,
        revision: str | None = "same",
        tested_revision: str | None = "same",
    ) -> Ep:
        r = self.revision if revision == "same" else revision
        item: dict[str, Any] = {
            "evidence_id": f"ev{len(self.evidence) + 1}",
            "kind": kind,
            "summary": summary,
            "observed_at": ts(self.day, 11),
            "revision": r,
            "exit_code": exit_code,
            "source_event_ids": [self._event()],
        }
        if criteria:
            tr = self.revision if tested_revision == "same" else tested_revision
            item["extensions"] = {ACC: {"criteria": criteria, "tested_revision": tr}}
        self.evidence.append(item)
        return self

    def lesson(
        self,
        problem: str,
        approach: str | None,
        *,
        symptoms: list[str],
        failed: list[str] | None = None,
        pre: list[str] | None = None,
        contra: list[str] | None = None,
        basis: str,
    ) -> Ep:
        self.lessons.append(
            {
                "lesson_id": f"l{len(self.lessons) + 1}",
                "problem": problem,
                "observed_symptoms": symptoms,
                "failed_approaches": failed or [],
                "successful_approach": approach,
                "preconditions": pre or [],
                "contraindications": contra or [],
                "versions": dict(self.env["versions"]),
                "verification_evidence_ids": [e["evidence_id"] for e in self.evidence],
                "source_episode_ids": [self.id],
                "confidence_basis": basis,
            }
        )
        return self

    def outcome(self, status: str) -> Ep:
        self.status = status
        return self

    def build(self) -> dict[str, Any]:
        ep: dict[str, Any] = {
            "episode_id": self.id,
            "task_summary": self.task,
            "environment": self.env,
            "observations": self.observations,
            "attempts": self.attempts,
            "outcome": {"status": self.status, "evidence": self.evidence},
            "lessons": self.lessons,
            "provenance": {
                "source": "synthetic-fixture:skill-foundry-demo",
                "event_ids": list(self.events),
                "redaction_applied": True,
            },
        }
        if self.lineage:
            ep["extensions"] = {"skill_foundry.task_lineage": self.lineage}
        return ep


